export function translate(locale: string | undefined, key: MessageKey, params: MessageParams = {}): string {
  const text = (locale === 'zh-CN' ? zhCN[key] : undefined) ?? en[key]
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match))
}
